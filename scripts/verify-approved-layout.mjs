import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(resolve(root, path), "utf8");
const tokens = read("src/styles/tokens.css");
const css = read("src/styles/global.css");
const sidebar = read("src/components/sidebar/Sidebar.tsx");
const contextual = read("src/components/sidebar/ContextualSidebar.tsx");
const chat = read("src/components/chat/ChatPanel.tsx");
const dashboard = read("src/components/workspace/WorkspaceDashboard.tsx");
assert.match(tokens, /--sidebar-width:\s*calc\(var\(--nav-rail-width\) \+ var\(--nav-contextual-width\)\)/);
assert.match(tokens, /--sidebar-collapsed-width:\s*var\(--nav-rail-width\)/);
assert.match(css, /\.app-shell > \.dual-sidebar\s*\{[^}]*width:\s*100%/);
assert.match(css, /\.icon-rail-bottom\s*\{[^}]*margin-top:\s*auto/);
assert.match(sidebar, /<IconRail/);
assert.match(sidebar, /<ContextualSidebar/);
assert.match(contextual, /Chats &amp; Projects|Chats & Projects/);
assert.match(contextual, /role="tab"/);
assert.match(chat, /<WorkspaceDashboard conversationId=\{activeConversationId\}/);
assert.match(dashboard, /<Composer conversationId=\{conversationId\}/);
console.log("PASS: approved dual-sidebar geometry and empty-conversation dashboard source contracts");
