#!/usr/bin/env node
/**
 * Generate effective window authority from capabilities + permission sets.
 * Does NOT claim raw-invoke denial was executed.
 *
 * Usage: npm run audit:tauri-capabilities
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const reportsDir = path.join(root, "reports");
const capsDir = path.join(root, "src-tauri", "capabilities");
const permsDir = path.join(root, "src-tauri", "permissions");
const commandName = "audit:tauri-capabilities";

function git(args) {
  return spawnSync("git", args, { cwd: root, encoding: "utf8" }).stdout.trim();
}

function sha256File(p) {
  return crypto.createHash("sha256").update(fs.readFileSync(p)).digest("hex");
}

function parseTomlFile(text, relativePath, byId) {
  // Permission sets: [[set]]
  const setBlocks = text.split("[[set]]").slice(1);
  for (const block of setBlocks) {
    const id = block.match(/identifier\s*=\s*"([^"]+)"/)?.[1];
    if (!id) continue;
    const perms = [];
    const arrayMatch = block.match(/permissions\s*=\s*\[([\s\S]*?)\]/);
    if (arrayMatch) {
      for (const m of arrayMatch[1].matchAll(/"([^"]+)"/g)) perms.push(m[1]);
    }
    byId.set(id, { source: relativePath, permissions: perms });
  }

  // Autogenerated allow/deny: [[permission]]
  const permBlocks = text.split("[[permission]]").slice(1);
  for (const block of permBlocks) {
    const id = block.match(/identifier\s*=\s*"([^"]+)"/)?.[1];
    if (!id) continue;
    const commandsAllow = [];
    const commandsDeny = [];
    const allowArr = block.match(/commands\.allow\s*=\s*\[([\s\S]*?)\]/);
    const denyArr = block.match(/commands\.deny\s*=\s*\[([\s\S]*?)\]/);
    if (allowArr) {
      for (const m of allowArr[1].matchAll(/"([^"]+)"/g)) commandsAllow.push(m[1]);
    }
    if (denyArr) {
      for (const m of denyArr[1].matchAll(/"([^"]+)"/g)) commandsDeny.push(m[1]);
    }
    byId.set(id, {
      source: relativePath,
      commandsAllow,
      commandsDeny,
    });
  }
}

function loadPermissionCatalog() {
  const byId = new Map();
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const name of fs.readdirSync(dir)) {
      const abs = path.join(dir, name);
      const st = fs.statSync(abs);
      if (st.isDirectory()) walk(abs);
      else if (name.endsWith(".toml")) {
        parseTomlFile(fs.readFileSync(abs, "utf8"), path.relative(root, abs), byId);
      }
    }
  };
  walk(permsDir);
  return byId;
}

function expandPermissions(entries, catalog, seen = new Set()) {
  const allows = new Set();
  const denies = new Set();
  const unresolved = [];
  const sources = [];
  for (const entry of entries) {
    if (seen.has(entry)) continue;
    seen.add(entry);
    sources.push(entry);
    if (entry.startsWith("core:") || entry.startsWith("shell:") || entry.includes(":")) {
      // Core/plugin permission identifiers — keep as-is.
      if (entry.includes("deny") || entry.startsWith("deny-")) denies.add(entry);
      else allows.add(entry);
      continue;
    }
    const item = catalog.get(entry);
    if (!item) {
      unresolved.push(entry);
      continue;
    }
    if (item.permissions) {
      const nested = expandPermissions(item.permissions, catalog, seen);
      nested.allows.forEach((a) => allows.add(a));
      nested.denies.forEach((d) => denies.add(d));
      unresolved.push(...nested.unresolved);
      continue;
    }
    (item.commandsAllow || []).forEach((c) => allows.add(c));
    (item.commandsDeny || []).forEach((c) => denies.add(c));
  }
  return {
    allows: [...allows].sort(),
    denies: [...denies].sort(),
    unresolved: [...new Set(unresolved)].sort(),
    sources,
  };
}

const FORBIDDEN_MAIN_CREATE = [
  "core:window:allow-create",
  "core:webview:allow-create-webview-window",
];

const catalog = loadPermissionCatalog();
const capabilities = fs
  .readdirSync(capsDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(fs.readFileSync(path.join(capsDir, f), "utf8")));

const windows = {};
for (const cap of capabilities) {
  const expanded = expandPermissions(cap.permissions || [], catalog);
  const key = (cap.windows || []).join(",") || cap.identifier;
  windows[key] = {
    capability: cap.identifier,
    windowMatchers: cap.windows || [],
    permissionEntries: cap.permissions || [],
    applicationCommandsAllow: expanded.allows.filter((a) => !a.includes(":")),
    applicationCommandsDeny: expanded.denies.filter((d) => !d.includes(":")),
    coreAndPluginAllows: expanded.allows.filter((a) => a.includes(":")),
    coreAndPluginDenies: expanded.denies.filter((d) => d.includes(":")),
    unresolved: expanded.unresolved,
  };
}

const mainCore = windows.main?.coreAndPluginAllows || [];
const policyViolations = FORBIDDEN_MAIN_CREATE.filter((p) => mainCore.includes(p));
const unresolvedAll = Object.values(windows).flatMap((w) => w.unresolved || []);
if (unresolvedAll.length) {
  policyViolations.push(...unresolvedAll.map((u) => `unresolved:${u}`));
}

const commit = git(["rev-parse", "HEAD"]);
const dirty = git(["status", "--porcelain"]).length > 0;
const packageLockHash = sha256File(path.join(root, "package-lock.json"));
const cargoLockHash = sha256File(path.join(root, "src-tauri", "Cargo.lock"));
let sourceFingerprint = null;
try {
  sourceFingerprint = JSON.parse(
    fs.readFileSync(path.join(reportsDir, "current-source-fingerprint.json"), "utf8"),
  ).sourceFingerprint;
} catch {
  sourceFingerprint = null;
}

let rawInvokeDenialTest = "not_run";
let rawInvokeEvidence = null;
try {
  const auth = JSON.parse(
    fs.readFileSync(path.join(reportsDir, "command-authority-results.json"), "utf8"),
  );
  if (auth.rawInvokeDenialTest === "passed" && auth.status === "generated_from_e2e") {
    rawInvokeDenialTest = "passed";
    rawInvokeEvidence = "command-authority-results.json";
  }
} catch {
  rawInvokeDenialTest = "not_run";
}

const ok = policyViolations.length === 0;
const report = {
  schemaVersion: 1,
  product: "Coreside",
  generatedAt: new Date().toISOString(),
  commit,
  dirty,
  sourceFingerprint,
  packageLockHash,
  cargoLockHash,
  platform: process.platform,
  architecture: process.arch,
  buildMode: "development",
  command: commandName,
  exitStatus: ok ? 0 : 1,
  status: ok ? "generated_from_capabilities" : "policy_violation",
  policyViolations,
  rawInvokeDenialTest,
  rawInvokeEvidence,
  note:
    rawInvokeDenialTest === "passed"
      ? "Generated from capabilities; raw-invoke denial proven by Journey 11 E2E evidence."
      : "Generated from active capability JSON and permission TOML. Does not prove runtime denial.",
  windows,
  publicBeta: "Not ready",
};

const inventory = {
  ...report,
  capabilities: capabilities.map((c) => ({
    identifier: c.identifier,
    windows: c.windows,
    permissions: c.permissions,
  })),
  permissionSetCount: [...catalog.keys()].filter((k) => !k.startsWith("allow-") && !k.startsWith("deny-")).length,
};

fs.mkdirSync(reportsDir, { recursive: true });
fs.writeFileSync(path.join(reportsDir, "effective-window-authority.json"), JSON.stringify(report, null, 2) + "\n");
fs.writeFileSync(path.join(reportsDir, "tauri-capability-inventory.json"), JSON.stringify(inventory, null, 2) + "\n");

console.log(
  JSON.stringify(
    {
      command: commandName,
      windowClasses: Object.keys(windows),
      policyViolations,
      rawInvokeDenialTest,
      rawInvokeEvidence,
      publicBeta: "Not ready",
      exitStatus: report.exitStatus,
    },
    null,
    2,
  ),
);
process.exit(ok ? 0 : 1);
